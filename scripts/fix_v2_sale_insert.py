from pathlib import Path

BAD = "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,'posted',?,?)"
GOOD = "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,'posted',?,?)"

for name in ("jewel_server/services.py", "scripts/apply_production_hardening_v2.py"):
    p = Path(name)
    text = p.read_text(encoding="utf-8")
    if BAD not in text:
        print("no bad placeholder pattern in", name)
        continue
    fixed = text.replace(BAD, GOOD)
    p.write_text(fixed, encoding="utf-8")
    print("fixed", name, "occurrences", text.count(BAD))

assert GOOD.count("?") == 38
